#!/usr/bin/env bash
# Bootstrap one TPU VM worker from an operator-generated, secret-free config.
#
# This script is copied to every worker by deploy_workers.sh. It is deliberately
# fail-closed: it never chooses, partitions, or formats a scratch device, and it
# mounts the explicitly configured NFS export only at the repository's canonical
# production artifact path.

set -euo pipefail
IFS=$'\n\t'
umask 077

readonly MIN_CONTROL_FREE_BYTES=10000000000
# Activation farming needs two simultaneous 8 GiB qualification probes plus
# an 8 GiB reserve. This may be a local disk or the worker-private /dev/shm
# tmpfs; the collective qualifier proves capacity, isolation, and throughput
# before either is authorized. SAE training's capture cache is a separate,
# unqualified capability and is deliberately not authorized by this bootstrap.
readonly MIN_LOCAL_FREE_BYTES=25769803776
readonly METADATA_ROOT="http://metadata.google.internal/computeMetadata/v1"

usage() {
  cat <<'EOF'
Usage: bootstrap_worker.sh --config PATH --bundle PATH

The config and Git bundle are generated by scripts/tpu/deploy_workers.sh.
Do not invoke this script with hand-written shell fragments or credentials.
EOF
}

log() {
  printf '[bootstrap:%s] %s\n' "$(hostname -s 2>/dev/null || hostname)" "$*"
}

die() {
  printf '[bootstrap:%s] ERROR: %s\n' \
    "$(hostname -s 2>/dev/null || hostname)" "$*" >&2
  exit 1
}

require_command() {
  command -v "$1" >/dev/null 2>&1 || die "required command is unavailable: $1"
}

sha256_file() {
  sha256sum "$1" | awk '{print $1}'
}

is_uint() {
  [[ "$1" =~ ^[0-9]+$ ]]
}

is_within() {
  local child=$1
  local parent=$2
  [[ "$child" == "$parent" || "$child" == "$parent/"* ]]
}

free_bytes() {
  local path=$1
  local value
  value=$(df -PB1 "$path" | awk 'NR == 2 {print $4}')
  is_uint "$value" || die "could not determine free bytes for $path"
  printf '%s\n' "$value"
}

require_free_bytes() {
  local path=$1
  local minimum=$2
  local label=$3
  local available
  available=$(free_bytes "$path")
  if (( available < minimum )); then
    die "$label has $available free bytes; at least $minimum are required"
  fi
  log "$label capacity is acceptable ($available free bytes)"
}

validate_absolute_path() {
  local name=$1
  local value=$2
  [[ "$value" =~ ^/[A-Za-z0-9._/@+-]+$ ]] || \
    die "$name must be an absolute path containing only safe characters"
  [[ "$(realpath -m "$value")" == "$value" ]] || \
    die "$name must already be canonical (no symlinked or '..' components): $value"
}

validate_config_value() {
  local key=$1
  local value=$2
  case "$key" in
    DEPLOYMENT_SCHEMA)
      [[ "$value" == "1" ]] || die "unsupported deployment schema: $value"
      ;;
    PROJECT_COMMIT|BUNDLE_SHA256|BOOTSTRAP_SHA256|EXPECTED_MAXTEXT_COMMIT)
      if [[ "$key" == "PROJECT_COMMIT" || "$key" == "EXPECTED_MAXTEXT_COMMIT" ]]; then
        [[ "$value" =~ ^[0-9a-f]{40}$ ]] || die "$key must be a lowercase 40-character Git SHA"
      else
        [[ "$value" =~ ^[0-9a-f]{64}$ ]] || die "$key must be a lowercase SHA-256"
      fi
      ;;
    GCP_PROJECT)
      [[ "$value" =~ ^[a-z][a-z0-9-]{4,61}[a-z0-9]$ ]] || die "invalid GCP_PROJECT"
      ;;
    EXPECTED_SERVICE_ACCOUNT)
      [[ "$value" =~ ^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+$ ]] || \
        die "invalid EXPECTED_SERVICE_ACCOUNT"
      ;;
    PROJECT_ROOT|LOCAL_BUFFER_ROOT)
      validate_absolute_path "$key" "$value"
      ;;
    BULK_GCS_ROOT)
      [[ "$value" =~ ^gs://[a-z0-9][a-z0-9._-]*/[A-Za-z0-9._/-]+$ ]] || \
        die "BULK_GCS_ROOT must be a non-root gs:// path"
      [[ "$value" != */ ]] || die "BULK_GCS_ROOT must not end with '/'"
      ;;
    NFS_SERVER)
      [[ "$value" =~ ^[A-Za-z0-9.-]+$ ]] || die "invalid NFS_SERVER"
      ;;
    NFS_EXPORT)
      [[ "$value" =~ ^/[A-Za-z0-9._/-]+$ ]] || die "invalid NFS_EXPORT"
      [[ "$value" != */ ]] || die "NFS_EXPORT must not end with '/'"
      ;;
    UV_VERSION)
      [[ "$value" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "invalid UV_VERSION"
      ;;
    *)
      die "unknown deployment config key: $key"
      ;;
  esac
}

DEPLOYMENT_SCHEMA=''
PROJECT_COMMIT=''
BUNDLE_SHA256=''
BOOTSTRAP_SHA256=''
EXPECTED_MAXTEXT_COMMIT=''
GCP_PROJECT=''
EXPECTED_SERVICE_ACCOUNT=''
PROJECT_ROOT=''
LOCAL_BUFFER_ROOT=''
BULK_GCS_ROOT=''
NFS_SERVER=''
NFS_EXPORT=''
UV_VERSION=''

load_config() {
  local config_file=$1
  local key
  local value
  local seen='|'

  [[ -f "$config_file" ]] || die "deployment config does not exist: $config_file"
  while IFS='=' read -r key value || [[ -n "$key" ]]; do
    [[ -n "$key" ]] || continue
    [[ "$key" != \#* ]] || continue
    [[ -n "$value" ]] || die "deployment config value is empty: $key"
    case "$seen" in
      *"|$key|"*) die "duplicate deployment config key: $key" ;;
    esac
    validate_config_value "$key" "$value"
    seen="${seen}${key}|"
    case "$key" in
      DEPLOYMENT_SCHEMA) DEPLOYMENT_SCHEMA=$value ;;
      PROJECT_COMMIT) PROJECT_COMMIT=$value ;;
      BUNDLE_SHA256) BUNDLE_SHA256=$value ;;
      BOOTSTRAP_SHA256) BOOTSTRAP_SHA256=$value ;;
      EXPECTED_MAXTEXT_COMMIT) EXPECTED_MAXTEXT_COMMIT=$value ;;
      GCP_PROJECT) GCP_PROJECT=$value ;;
      EXPECTED_SERVICE_ACCOUNT) EXPECTED_SERVICE_ACCOUNT=$value ;;
      PROJECT_ROOT) PROJECT_ROOT=$value ;;
      LOCAL_BUFFER_ROOT) LOCAL_BUFFER_ROOT=$value ;;
      BULK_GCS_ROOT) BULK_GCS_ROOT=$value ;;
      NFS_SERVER) NFS_SERVER=$value ;;
      NFS_EXPORT) NFS_EXPORT=$value ;;
      UV_VERSION) UV_VERSION=$value ;;
    esac
  done < "$config_file"

  local required
  for required in \
    DEPLOYMENT_SCHEMA PROJECT_COMMIT BUNDLE_SHA256 BOOTSTRAP_SHA256 \
    EXPECTED_MAXTEXT_COMMIT GCP_PROJECT EXPECTED_SERVICE_ACCOUNT PROJECT_ROOT \
    LOCAL_BUFFER_ROOT BULK_GCS_ROOT NFS_SERVER NFS_EXPORT UV_VERSION; do
    [[ "$seen" == *"|$required|"* ]] || die "missing deployment config key: $required"
  done
}

install_system_packages() {
  require_command sudo
  sudo -n true >/dev/null 2>&1 || die "passwordless sudo is required on the TPU VM"
  log "installing bootstrap packages"
  export DEBIAN_FRONTEND=noninteractive
  sudo apt-get update
  sudo apt-get install -y --no-install-recommends \
    ca-certificates curl git jq nfs-common tmux util-linux
}

ensure_deployment_user_linger() {
  local deployment_user
  local linger

  deployment_user=$(id -un)
  [[ -n "$deployment_user" ]] || die "could not identify the deployment user"
  require_command loginctl
  log "enabling systemd linger for $deployment_user so logind RemoveIPC cannot purge /dev/shm caches after SSH logout"
  sudo -n loginctl enable-linger "$deployment_user"
  linger=$(loginctl show-user "$deployment_user" -p Linger --value)
  [[ "$linger" == "yes" ]] || \
    die "systemd linger for $deployment_user is '$linger'; expected exactly 'yes'"
  log "systemd linger is enabled for $deployment_user"
}

verify_worker_identity() {
  local actual_service_account=''
  local attempt
  require_command curl
  require_command gcloud

  for attempt in 1 2 3 4 5; do
    actual_service_account=$(curl -fsS \
      -H 'Metadata-Flavor: Google' \
      "$METADATA_ROOT/instance/service-accounts/default/email" || true)
    [[ -n "$actual_service_account" ]] && break
    sleep 1
  done
  [[ "$actual_service_account" == "$EXPECTED_SERVICE_ACCOUNT" ]] || \
    die "worker service account is '$actual_service_account'; expected '$EXPECTED_SERVICE_ACCOUNT'"

  gcloud storage ls --project="$GCP_PROJECT" "$BULK_GCS_ROOT" >/dev/null || \
    die "gcloud cannot list the configured GCS root: $BULK_GCS_ROOT"
  log "metadata identity and gcloud GCS access are correct"
}

deploy_exact_checkout() {
  local bundle=$1
  local current_commit
  local fetched_commit
  local checkout_status
  local committed_bootstrap_hash

  [[ -f "$bundle" ]] || die "Git bundle does not exist: $bundle"
  [[ "$(sha256_file "$bundle")" == "$BUNDLE_SHA256" ]] || die "Git bundle SHA-256 mismatch"
  [[ "$(sha256_file "$0")" == "$BOOTSTRAP_SHA256" ]] || \
    die "running bootstrap script SHA-256 mismatch"

  if [[ -e "$PROJECT_ROOT" ]]; then
    [[ -d "$PROJECT_ROOT/.git" ]] || \
      die "PROJECT_ROOT exists but is not a Git checkout: $PROJECT_ROOT"
    checkout_status=$(git -C "$PROJECT_ROOT" status --porcelain --untracked-files=all)
    [[ -z "$checkout_status" ]] || \
      die "existing PROJECT_ROOT is dirty; refusing to overwrite it"
    git -C "$PROJECT_ROOT" fetch "$bundle" HEAD
    fetched_commit=$(git -C "$PROJECT_ROOT" rev-parse FETCH_HEAD)
    [[ "$fetched_commit" == "$PROJECT_COMMIT" ]] || \
      die "bundle HEAD is $fetched_commit; expected $PROJECT_COMMIT"
    git -C "$PROJECT_ROOT" checkout --detach "$PROJECT_COMMIT"
  else
    [[ -d "$(dirname "$PROJECT_ROOT")" ]] || \
      install -d -m 0755 "$(dirname "$PROJECT_ROOT")"
    git clone --no-checkout "$bundle" "$PROJECT_ROOT"
    git -C "$PROJECT_ROOT" checkout --detach "$PROJECT_COMMIT"
  fi

  current_commit=$(git -C "$PROJECT_ROOT" rev-parse HEAD)
  [[ "$current_commit" == "$PROJECT_COMMIT" ]] || \
    die "deployed checkout is $current_commit; expected $PROJECT_COMMIT"
  checkout_status=$(git -C "$PROJECT_ROOT" status --porcelain --untracked-files=all)
  [[ -z "$checkout_status" ]] || die "deployed checkout is unexpectedly dirty"

  committed_bootstrap_hash=$(
    git -C "$PROJECT_ROOT" show HEAD:scripts/tpu/bootstrap_worker.sh | sha256sum | awk '{print $1}'
  )
  [[ "$committed_bootstrap_hash" == "$BOOTSTRAP_SHA256" ]] || \
    die "deployed commit does not contain the bootstrap script being executed"
  log "checked out exact commit $PROJECT_COMMIT"
}

mount_control_plane() {
  local artifact_root="$PROJECT_ROOT/artifacts/gemma4_v1/production"
  local expected_source="$NFS_SERVER:$NFS_EXPORT"
  local actual_source
  local filesystem_type
  local mount_options
  local probe

  [[ ! -L "$artifact_root" ]] || die "artifact root must not be a symlink: $artifact_root"
  if mountpoint -q "$artifact_root"; then
    [[ -d "$artifact_root" ]] || die "mounted artifact root is not a directory"
    IFS=' ' read -r actual_source filesystem_type mount_options < <(
      findmnt -rn -o SOURCE,FSTYPE,OPTIONS --mountpoint "$artifact_root"
    )
    [[ "$actual_source" == "$expected_source" ]] || \
      die "artifact root is mounted from '$actual_source'; expected '$expected_source'"
    if ! has_positive_lookup_cache "$mount_options"; then
      log "unmounting NFS control plane before enabling lookupcache=positive"
      # NFS-specific cache policy is not reliably changed by a generic remount.
      # Bootstrap runs before any workload, so a normal unmount must succeed;
      # never use force/lazy unmount because that could split control-plane state.
      sudo umount "$artifact_root"
      sudo mount -t nfs -o rw,hard,timeo=600,retrans=2,lookupcache=positive \
        "$expected_source" "$artifact_root"
      IFS=' ' read -r actual_source filesystem_type mount_options < <(
        findmnt -rn -o SOURCE,FSTYPE,OPTIONS --mountpoint "$artifact_root"
      )
    fi
  else
    if [[ ! -e "$artifact_root" ]]; then
      sudo install -d -m 0755 -o "$(id -un)" -g "$(id -gn)" "$artifact_root"
    fi
    [[ -d "$artifact_root" ]] || die "artifact root exists but is not a directory"
    if [[ -n "$(find "$artifact_root" -mindepth 1 -maxdepth 1 -print -quit)" ]]; then
      die "unmounted artifact root is not empty: $artifact_root"
    fi
    log "mounting NFS control plane $expected_source at $artifact_root"
    sudo mount -t nfs -o rw,hard,timeo=600,retrans=2,lookupcache=positive \
      "$expected_source" "$artifact_root"
    IFS=' ' read -r actual_source filesystem_type mount_options < <(
      findmnt -rn -o SOURCE,FSTYPE,OPTIONS --mountpoint "$artifact_root"
    )
  fi

  case "$filesystem_type" in
    nfs|nfs4) ;;
    *) die "artifact root filesystem is '$filesystem_type', not NFS" ;;
  esac
  [[ "$actual_source" == "$expected_source" ]] || \
    die "mounted NFS source is '$actual_source'; expected '$expected_source'"
  has_positive_lookup_cache "$mount_options" || \
    die "NFS control plane must be mounted with lookupcache=positive"

  if [[ ! -w "$artifact_root" ]]; then
    sudo chown "$(id -u):$(id -g)" "$artifact_root"
  fi
  [[ -w "$artifact_root" ]] || die "artifact root is not writable by $(id -un)"
  require_free_bytes "$artifact_root" "$MIN_CONTROL_FREE_BYTES" "shared control plane"

  probe=$(mktemp "$artifact_root/.bootstrap-write.$(hostname -s).XXXXXX")
  printf '%s\n' "$PROJECT_COMMIT" > "$probe"
  sync "$probe"
  rm -- "$probe"
  log "NFS control plane is mounted directly at $artifact_root"
}

has_mount_option() {
  local options=$1
  local required=$2
  [[ ",$options," == *",$required,"* ]]
}

has_positive_lookup_cache() {
  local options=$1
  # util-linux/findmnt renders the kernel's accepted "positive" value as
  # either lookupcache=positive or the abbreviated lookupcache=pos.
  has_mount_option "$options" lookupcache=positive || \
    has_mount_option "$options" lookupcache=pos
}

validate_local_buffer_filesystem() {
  local path=$1
  local mount_target=$2
  local source=$3
  local filesystem_type=$4
  local options=$5
  case "$filesystem_type" in
    nfs|nfs4|cifs|smb*|fuse*|9p|ceph|ceph-fuse|lustre|glusterfs|afs|gpfs|gcsfuse)
      die "LOCAL_BUFFER_ROOT resolves to shared/remote filesystem type '$filesystem_type'"
      ;;
    ext2|ext3|ext4|xfs|btrfs)
      ;;
    tmpfs)
      [[ "$path" == /dev/shm/* ]] || \
        die "tmpfs LOCAL_BUFFER_ROOT must be strictly below /dev/shm"
      [[ "$mount_target" == "/dev/shm" ]] || \
        die "tmpfs LOCAL_BUFFER_ROOT must resolve to the direct /dev/shm mount, not '$mount_target'"
      [[ "$source" == "tmpfs" ]] || \
        die "/dev/shm source is '$source'; expected the kernel tmpfs source"
      has_mount_option "$options" rw || die "/dev/shm must be mounted read-write"
      has_mount_option "$options" nosuid || die "/dev/shm must be mounted nosuid"
      has_mount_option "$options" nodev || die "/dev/shm must be mounted nodev"
      ;;
    *)
      die "LOCAL_BUFFER_ROOT filesystem type '$filesystem_type' is not an approved host-local filesystem"
      ;;
  esac
}

prepare_local_buffer() {
  local artifact_root="$PROJECT_ROOT/artifacts/gemma4_v1/production"
  local inspect_path
  local parent
  local filesystem_type
  local mount_options
  local mount_target
  local source
  local probe

  [[ "$LOCAL_BUFFER_ROOT" != "/" ]] || die "LOCAL_BUFFER_ROOT must not be '/'"
  is_within "$LOCAL_BUFFER_ROOT" "$PROJECT_ROOT" && \
    die "LOCAL_BUFFER_ROOT must not be inside PROJECT_ROOT"
  is_within "$PROJECT_ROOT" "$LOCAL_BUFFER_ROOT" && \
    die "LOCAL_BUFFER_ROOT must not contain PROJECT_ROOT"
  is_within "$LOCAL_BUFFER_ROOT" "$artifact_root" && \
    die "LOCAL_BUFFER_ROOT must not be inside the shared artifact root"

  if [[ -e "$LOCAL_BUFFER_ROOT" ]]; then
    [[ -d "$LOCAL_BUFFER_ROOT" && ! -L "$LOCAL_BUFFER_ROOT" ]] || \
      die "LOCAL_BUFFER_ROOT must be a real directory, not a file or symlink"
    inspect_path=$LOCAL_BUFFER_ROOT
  else
    parent=$(dirname "$LOCAL_BUFFER_ROOT")
    [[ -d "$parent" && ! -L "$parent" ]] || \
      die "LOCAL_BUFFER_ROOT parent must already exist and must not be a symlink: $parent"
    inspect_path=$parent
  fi

  IFS=' ' read -r mount_target source filesystem_type mount_options < <(
    findmnt -rn -o TARGET,SOURCE,FSTYPE,OPTIONS --target "$inspect_path"
  )
  [[ -n "$mount_target" && -n "$source" && -n "$filesystem_type" && -n "$mount_options" ]] || \
    die "cannot identify filesystem for LOCAL_BUFFER_ROOT parent: $inspect_path"
  validate_local_buffer_filesystem \
    "$LOCAL_BUFFER_ROOT" "$mount_target" "$source" "$filesystem_type" "$mount_options"
  require_free_bytes "$inspect_path" "$MIN_LOCAL_FREE_BYTES" "local-buffer filesystem"

  if [[ ! -e "$LOCAL_BUFFER_ROOT" ]]; then
    sudo install -d -m 0750 -o "$(id -un)" -g "$(id -gn)" "$LOCAL_BUFFER_ROOT"
  fi
  [[ -d "$LOCAL_BUFFER_ROOT" && ! -L "$LOCAL_BUFFER_ROOT" ]] || \
    die "LOCAL_BUFFER_ROOT creation did not produce a real directory"
  [[ -w "$LOCAL_BUFFER_ROOT" ]] || die "LOCAL_BUFFER_ROOT is not writable by $(id -un)"

  IFS=' ' read -r mount_target source filesystem_type mount_options < <(
    findmnt -rn -o TARGET,SOURCE,FSTYPE,OPTIONS --target "$LOCAL_BUFFER_ROOT"
  )
  validate_local_buffer_filesystem \
    "$LOCAL_BUFFER_ROOT" "$mount_target" "$source" "$filesystem_type" "$mount_options"
  require_free_bytes "$LOCAL_BUFFER_ROOT" "$MIN_LOCAL_FREE_BYTES" "local buffer"

  probe=$(mktemp "$LOCAL_BUFFER_ROOT/.bootstrap-write.$(hostname -s).XXXXXX")
  printf '%s\n' "$PROJECT_COMMIT" > "$probe"
  sync "$probe"
  rm -- "$probe"
  log "using explicit local buffer $LOCAL_BUFFER_ROOT ($source, $filesystem_type)"
  log "cross-worker privacy remains gated by the collective qualify-storage command"
}

install_python_environment() {
  local uv_bin="$HOME/.local/bin/uv"
  local actual_uv_version
  local actual_python_version
  local actual_maxtext_commit

  log "installing pinned uv $UV_VERSION"
  curl -LsSf "https://astral.sh/uv/$UV_VERSION/install.sh" | \
    env UV_INSTALL_DIR="$HOME/.local/bin" UV_NO_MODIFY_PATH=1 sh
  [[ -x "$uv_bin" ]] || die "uv installer did not create $uv_bin"
  actual_uv_version=$($uv_bin --version | awk '{print $2}')
  [[ "$actual_uv_version" == "$UV_VERSION" ]] || \
    die "installed uv version is $actual_uv_version; expected $UV_VERSION"

  "$uv_bin" python install 3.12
  log "syncing the frozen TPU environment"
  (
    cd "$PROJECT_ROOT"
    "$uv_bin" sync --frozen --extra tpu --python 3.12
  )
  [[ -x "$PROJECT_ROOT/.venv/bin/python" ]] || die "uv did not create the project environment"
  actual_python_version=$(
    "$PROJECT_ROOT/.venv/bin/python" -c \
      'import platform; print(platform.python_version())'
  )
  [[ "$actual_python_version" == 3.12.* ]] || \
    die "project Python is $actual_python_version; expected 3.12.x"

  actual_maxtext_commit=$(
    cd "$PROJECT_ROOT"
    .venv/bin/python -c \
      'from moe_sae.runtime import installed_maxtext_commit; print(installed_maxtext_commit() or "")'
  )
  [[ "$actual_maxtext_commit" == "$EXPECTED_MAXTEXT_COMMIT" ]] || \
    die "installed MaxText commit is '$actual_maxtext_commit'; expected '$EXPECTED_MAXTEXT_COMMIT'"
  log "Python $actual_python_version and pinned MaxText are installed"
}

verify_python_adc() {
  local python="$PROJECT_ROOT/.venv/bin/python"
  "$python" - "$BULK_GCS_ROOT" <<'PY'
import sys
from google.cloud import storage

uri = sys.argv[1]
bucket_name, separator, prefix = uri[5:].partition("/")
if not separator or not prefix:
    raise SystemExit("BULK_GCS_ROOT must include a bucket and prefix")
client = storage.Client()
if next(client.list_blobs(bucket_name, prefix=prefix.rstrip("/") + "/", max_results=1), None) is None:
    raise SystemExit(f"no staged object is visible below {uri}")
print(f"Python ADC can read gs://{bucket_name}/{prefix}")
PY
}

main() {
  local config_file=''
  local bundle_file=''
  local status

  while (( $# > 0 )); do
    case "$1" in
      --config)
        (( $# >= 2 )) || die "--config requires a path"
        config_file=$2
        shift 2
        ;;
      --bundle)
        (( $# >= 2 )) || die "--bundle requires a path"
        bundle_file=$2
        shift 2
        ;;
      -h|--help)
        usage
        exit 0
        ;;
      *)
        die "unknown argument: $1"
        ;;
    esac
  done
  [[ -n "$config_file" ]] || die "--config is required"
  [[ -n "$bundle_file" ]] || die "--bundle is required"

  require_command sha256sum
  require_command awk
  require_command realpath
  load_config "$config_file"
  install_system_packages
  ensure_deployment_user_linger
  require_command findmnt
  require_command mountpoint
  verify_worker_identity
  deploy_exact_checkout "$bundle_file"
  mount_control_plane
  prepare_local_buffer
  install_python_environment
  verify_python_adc

  require_free_bytes "$LOCAL_BUFFER_ROOT" "$MIN_LOCAL_FREE_BYTES" "local buffer after dependency install"
  status=$(git -C "$PROJECT_ROOT" status --porcelain --untracked-files=all)
  [[ -z "$status" ]] || die "bootstrap left the production checkout dirty"
  log "READY commit=$PROJECT_COMMIT project=$PROJECT_ROOT local_buffer=$LOCAL_BUFFER_ROOT"
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
