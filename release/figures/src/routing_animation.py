#!/usr/bin/env python3
"""Animated routing schematic for "The Router Already Knows".

The animation builds Figure 1 one step at a time: a token enters the frozen
router, the router selects experts, the selected experts open their
dictionary banks, each bank selects four features, and the two training seams
appear. Every frame is drawn with the same TikZ code as Figure 1, and the
held frame is exactly Figure 1.

Two modes:

    python3 routing_animation.py OUT.tex
        Write a standalone LaTeX file with one page per frame.

    python3 routing_animation.py --encode FRAMES_DIR OUT_DIR
        Encode rasterized frames (FRAMES_DIR/f-*.png, in page order) as
        OUT_DIR/routing-schematic.gif and OUT_DIR/routing-schematic.mp4.

build.sh runs both, with pdflatex and pdftoppm in between.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

FPS = 20

# Timeline in seconds: (start, duration) of each step.
T = {
    "token": (0.30, 0.40),
    "in": (0.70, 0.50),
    "sel76": (1.30, 0.60),
    "sel79": (1.70, 0.60),
    "link76": (2.30, 0.50),
    "link79": (2.40, 0.50),
    "address": (2.60, 0.60),
    "open76": (2.80, 0.60),
    "open79": (2.90, 0.60),
    "tally": (5.10, 0.60),
    "panel": (5.90, 0.50),
    "sae": (6.20, 0.60),
    "sae_arrows": (6.60, 0.50),
    "tc": (7.00, 0.60),
    "tc_arrows": (7.40, 0.50),
    "gnote": (7.90, 0.50),
    "reset": (11.00, 0.80),
}
DOT_FADE = 0.25
# Bank dots selected in Figure 1, with the time each one fills.
DOTS = {
    76: [(1, 3.60), (2, 3.90), (4, 4.20), (6, 4.50)],
    79: [(0, 3.75), (3, 4.05), (4, 4.35), (7, 4.65)],
}
DURATION = T["reset"][0] + T["reset"][1]

# Figure 1's natural bounding box, fixed so every frame has the same canvas.
BBOX = r"\useasboundingbox (-9.44713pt,-80.25166pt) rectangle (388.88277pt,69.93849pt);"

PREAMBLE = r"""\documentclass[class=article,11pt,tikz,border=6pt]{standalone}
% Generated by routing_animation.py: one page per frame.
\usepackage[T1]{fontenc}
\usepackage[sc]{mathpazo}
\linespread{1.045}
\usepackage{amsmath,amssymb}
\usepackage{xcolor}
\usetikzlibrary{arrows.meta,calc}
\begin{document}
"""

PICTURE_OPTIONS = r"""\begin{tikzpicture}[
  font=\small,
  >={Stealth[length=4.2pt,width=3.2pt]},
  exp/.style={draw, minimum width=9.5mm, minimum height=5mm, inner sep=1pt},
]"""


def ease(x: float) -> float:
    x = min(max(x, 0.0), 1.0)
    return x * x * (3.0 - 2.0 * x)


def ramp(t: float, step: str) -> float:
    start, duration = T[step]
    return ease((t - start) / duration)


def on(v: float) -> bool:
    return v >= 0.999


def off(v: float) -> bool:
    return v <= 0.001


def op(v: float) -> str:
    """TikZ opacity option ('' when fully opaque)."""
    return "" if on(v) else f"opacity={v:.3f}, "


def mix(lo: float, hi: float, s: float) -> str:
    """black!<pct> between lo and hi percent."""
    return f"black!{lo + (hi - lo) * s:.1f}"


def grow(start: str, end: str, g: float) -> str:
    """Path from start toward end, a fraction g of the way."""
    return f"{start} -- ($({start[1:-1]})!{g:.4f}!({end[1:-1]})$)"


def frame(t: float) -> str:
    reset = ramp(t, "reset")
    keep = 1.0 - reset

    def state(step: str) -> float:  # cross-fades and colour changes
        return ramp(t, step) * keep

    out: list[str] = [PICTURE_OPTIONS, BBOX]
    add = out.append

    # Headings.
    add(r"\node[font=\footnotesize\scshape] at (2.05,2.25) {route};")
    s = state("address")
    if not off(s):
        add(rf"\node[{op(s)}font=\footnotesize\scshape] at (7.05,2.25) {{address}};")
    s = state("panel")
    if not off(s):
        add(rf"\node[{op(s)}font=\footnotesize\scshape] at (11.55,2.25) {{reconstruct or predict}};")

    # Token and router.
    s = state("token")
    add(rf"\node[{op(s) if not off(s) else 'opacity=0, '}circle, draw, minimum size=6.5mm, inner sep=0pt] (t) at (0,0) {{$t$}};")
    add(r"\node[circle, draw, minimum size=13.5mm, inner sep=0pt, font=\footnotesize\scshape] (r) at (1.85,0) {router};")
    add(r"\node[font=\scriptsize\itshape, anchor=north] at (1.85,-0.72) {frozen};")
    g = ramp(t, "in")
    if on(g) and on(keep):
        add(r"\draw[->] (t) -- (r);")
    elif not off(g) and not off(keep):
        add(rf"\draw[{op(keep)}->] {grow('(t.east)', '(r.west)', g)};")

    # Experts. E76 and E79 turn from unselected grey to selected black.
    add(r"\node[exp, draw=black!35, text=black!50] (e1)   at (4.15, 1.6) {$E_{1}$};")
    for name, num, y, step in (("e37", 76, "0.8", "sel76"), ("e94", 79, "-0.8", "sel79")):
        s = state(step)
        if on(s):
            add(rf"\node[exp, line width=0.8pt]            ({name})  at (4.15,{y:>5}) {{$E_{{{num}}}$}};")
        else:
            add(rf"\node[exp, line width={0.4 + 0.4 * s:.3f}pt, draw={mix(35, 100, s)}, text={mix(50, 100, s)}] ({name}) at (4.15,{y}) {{$E_{{{num}}}$}};")
        if name == "e37":
            add(r"\node                                    (ed)   at (4.15, 0.02) {$\vdots$};")
    add(r"\node[exp, draw=black!35, text=black!50] (e128) at (4.15,-1.6) {$E_{128}$};")

    # Router fan: grey to every expert; bold arrows grow to the selected two.
    add(r"\draw[black!30] (r.east) -- (e1.west);")
    add(r"\draw[black!30] (r.east) -- (e128.west);")
    add(r"\draw[black!18] (r.east) -- ($(ed.west)+(0,0.16)$);")
    add(r"\draw[black!18] (r.east) -- ($(ed.west)+(0,-0.12)$);")
    for name, step in (("e37", "sel76"), ("e94", "sel79")):
        s = state(step)
        if not on(s):
            add(rf"\draw[{op(1 - s)}black!30] (r.east) -- ({name}.west);")
    for name, step in (("e37", "sel76"), ("e94", "sel79")):
        g = ramp(t, step)
        if on(g) and on(keep):
            add(rf"\draw[->, line width=0.8pt] (r.east) -- ({name}.west);")
        elif not off(g) and not off(keep):
            add(rf"\draw[{op(keep)}->, line width=0.8pt] {grow('(r.east)', f'({name}.west)', g)};")

    # Dictionary banks.
    def closed_bank(y: str, num: int, alpha: float = 1.0) -> None:
        if off(alpha):
            return
        a = op(alpha)
        add(rf"\draw[{a}rounded corners=1pt, black!35, dash pattern=on 2pt off 1.5pt] (5.6,{y}-0.25) rectangle (8.55,{y}+0.25);")
        if on(alpha):
            add(rf"\node[anchor=west, black!50] at (5.62,{y}) {{$D_{{{num}}}$}};")
            add(rf"\foreach \k in {{0,...,7}} {{\draw[black!35, line width=0.4pt] (6.68+\k*0.245,{y}) circle (0.068);}}")

    def bank(y: str, num: int, step: str) -> None:
        s = state(step)
        dots = DOTS[num]
        if on(s) and all(on(ease((t - start) / DOT_FADE) * keep) for _, start in dots):
            idx = ",".join(str(k) for k, _ in dots)
            add(rf"\draw[rounded corners=1pt, line width=0.6pt] (5.6,{y}-0.25) rectangle (8.55,{y}+0.25);")
            add(rf"\node[anchor=west] at (5.62,{y}) {{$D_{{{num}}}$}};")
            add(rf"\foreach \k in {{0,...,7}} {{\draw[line width=0.45pt] (6.68+\k*0.245,{y}) circle (0.068);}}")
            add(rf"\foreach \k in {{{idx}}} {{\fill (6.68+\k*0.245,{y}) circle (0.068);}}")
            return
        if off(s):
            closed_bank(y, num)
            return
        closed_bank(y, num, alpha=1 - s)
        add(rf"\draw[{op(s)}rounded corners=1pt, line width=0.6pt] (5.6,{y}-0.25) rectangle (8.55,{y}+0.25);")
        add(rf"\node[anchor=west, text={mix(50, 100, s)}] at (5.62,{y}) {{$D_{{{num}}}$}};")
        add(rf"\foreach \k in {{0,...,7}} {{\draw[{mix(35, 100, s)}, line width={0.4 + 0.05 * s:.3f}pt] (6.68+\k*0.245,{y}) circle (0.068);}}")
        for k, start in dots:
            f = ease((t - start) / DOT_FADE) * keep
            if not off(f):
                add(rf"\fill[{op(f)}] (6.68+{k}*0.245,{y}) circle (0.068);")

    closed_bank("1.6", 1)
    bank("0.8", 76, "open76")
    add(r"\node at (7.07,0.02) {$\vdots$};")
    bank("-0.8", 79, "open79")
    closed_bank("-1.6", 128)

    # Expert-to-bank links: grey dotted until the bank's expert is selected.
    add(r"\draw[black!35, densely dotted] (e1.east) -- (5.6,1.6);")
    add(r"\draw[black!35, densely dotted] (e128.east) -- (5.6,-1.6);")
    for name, y, step in (("e37", "0.8", "link76"), ("e94", "-0.8", "link79")):
        s = state(step)
        g = ramp(t, step)
        if not on(s):
            add(rf"\draw[{op(1 - s)}black!35, densely dotted] ({name}.east) -- (5.6,{y});")
        if on(g) and on(keep):
            add(rf"\draw[line width=0.6pt] ({name}.east) -- (5.6,{y});")
        elif not off(g) and not off(keep):
            add(rf"\draw[{op(keep)}line width=0.6pt] {grow(f'({name}.east)', f'(5.6,{y})', g)};")

    # Right panel: the two seams.
    s = state("panel")
    if not off(s):
        add(rf"\draw[{op(s)}black!22] (9.25,-1.95) -- (9.25,1.95);")
    for row, arrows in (("sae", "sae_arrows"), ("tc", "tc_arrows")):
        s = state(row)
        if off(s):
            continue
        a = op(s)
        if row == "sae":
            add(rf"\node[{a}font=\scriptsize\scshape, anchor=west] at (9.6,1.5) {{sae}};")
            add(rf"\node[{a}] (ys)  at (10.05,1.0) {{$y_{{t,s}}$}};")
            add(rf"\node[{a}draw, minimum width=8mm, minimum height=5mm] (ds) at (11.55,1.0) {{$D_i$}};")
            add(rf"\node[{a}] (yh1) at (13.05,1.0) {{$\hat y_{{t,s}}$}};")
            pairs = (("ys", "ds"), ("ds", "yh1"))
            caption = rf"\node[{a}font=\scriptsize\itshape] at (11.55,0.5) {{the output reconstructs itself}};"
        else:
            add(rf"\node[{a}font=\scriptsize\scshape, anchor=west] at (9.6,-0.2) {{transcoder}};")
            add(rf"\node[{a}] (xt)  at (10.05,-0.7) {{$x_{{t}}$}};")
            add(rf"\node[{a}draw, minimum width=8mm, minimum height=5mm] (dt) at (11.55,-0.7) {{$D_i$}};")
            add(rf"\node[{a}] (yh2) at (13.05,-0.7) {{$\hat y_{{t,s}}$}};")
            pairs = (("xt", "dt"), ("dt", "yh2"))
            caption = rf"\node[{a}font=\scriptsize\itshape] at (11.55,-1.2) {{the input predicts the output}};"
        g = ramp(t, arrows)
        if on(g) and on(keep):
            add(rf"\draw[->] ({pairs[0][0]}) -- ({pairs[0][1]}); \draw[->] ({pairs[1][0]}) -- ({pairs[1][1]});")
        elif not off(g) and not off(keep):
            for left, right in pairs:
                add(rf"\draw[{op(keep)}->] {grow(f'({left}.east)', f'({right}.west)', g)};")
        add(caption)
    s = state("gnote")
    if not off(s):
        add(rf"\node[{op(s)}font=\scriptsize] at (11.55,-1.72) {{$g_{{t,s}}$ enters the loss, not the bank}};")

    # Tally.
    s = state("tally")
    if not off(s):
        add(rf"\node[{op(s)}font=\small] at (6.6,-2.55) {{$128\times512$ stored\quad$\cdot$\quad$8\times512$ visible\quad$\cdot$\quad$8\times4$ selected}};")

    add(r"\end{tikzpicture}")
    return "\n".join(out)


def write_tex(path: Path) -> int:
    frames = round(DURATION * FPS)
    body = "\n\n".join(frame(i / FPS) for i in range(frames))
    path.write_text(PREAMBLE + body + "\n\\end{document}\n", encoding="utf-8")
    return frames


def encode(frames_dir: Path, out_dir: Path) -> None:
    pattern = str(frames_dir / "f-%03d.png")
    palette = frames_dir / "palette.png"
    common = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-framerate", str(FPS), "-start_number", "1", "-i", pattern]
    subprocess.run(common + ["-vf", "palettegen=max_colors=96:stats_mode=full:reserve_transparent=0", str(palette)], check=True)
    subprocess.run(
        common + ["-i", str(palette), "-lavfi", "paletteuse=dither=none:diff_mode=rectangle", "-loop", "0", str(out_dir / "routing-schematic.gif")],
        check=True,
    )
    subprocess.run(
        common + ["-vf", "pad=ceil(iw/2)*2:ceil(ih/2)*2:color=white", "-c:v", "libx264", "-pix_fmt", "yuv420p",
                  "-crf", "18", "-preset", "slow", "-movflags", "+faststart", str(out_dir / "routing-schematic.mp4")],
        check=True,
    )


def main(argv: list[str]) -> int:
    if len(argv) == 2:
        n = write_tex(Path(argv[1]))
        print(f"wrote {n} frames ({DURATION:.1f} s at {FPS} fps)")
        return 0
    if len(argv) == 4 and argv[1] == "--encode":
        encode(Path(argv[2]), Path(argv[3]))
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
